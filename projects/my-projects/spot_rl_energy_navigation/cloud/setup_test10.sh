#!/usr/bin/env bash
# Fresh installation, or reuse only the software installed for test9.
set -Eeuo pipefail
PROJECT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
if [[ ! -d "$PROJECT/spot_rl_energy_navigation/cloud" ]]; then
    PROJECT="$(cd "$PROJECT/../.." && pwd)"
fi
CLOUD="$PROJECT/spot_rl_energy_navigation/cloud"
if [[ "${1:-}" == --help || "${1:-}" == -h ]]; then
    cat <<'HELP'
Usage: bash setup_test10.sh [setup.sh options]
       bash setup_test10.sh --reuse-existing /root/spot-test9-sac-cloud [--skip-probe]
       bash setup_test10.sh --check-only
Fresh setup downloads Isaac Sim/Isaac Lab and checks two robots, without training.
Reuse checks the existing software and writes a NEW env.sh for test10. Keep the
old software directory until training finishes. No test9 run or policy is loaded.
HELP
    exit 0
fi
if [[ "${1:-}" != --reuse-existing ]]; then
    # Ignore a previous experiment's sourced env.sh. Explicit --runtime-dir
    # remains available; reusing test9 intentionally uses the branch below.
    exec env SPOT_RUNTIME_DIR="$PROJECT/.spot-runtime" \
        SPOT_ZED_USD="$PROJECT/.cloud_assets/ZED_X.usdc" \
        bash "$CLOUD/setup.sh" --experiment train_general_big_map_test10_SAC "$@"
fi
[[ $# -ge 2 ]] || { echo 'Missing existing project directory.' >&2; exit 2; }
OLD_PROJECT="$(cd -- "$2" && pwd)"
shift 2
SKIP_PROBE=0
if [[ "${1:-}" == --skip-probe ]]; then SKIP_PROBE=1; shift; fi
[[ $# == 0 ]] || { echo 'Unexpected reuse option; see --help.' >&2; exit 2; }
[[ -f "$OLD_PROJECT/spot_rl_energy_navigation/cloud/env.sh" ]] || {
    echo 'Existing cloud/env.sh not found. Use fresh setup instead.' >&2; exit 1;
}
python3 "$CLOUD/verify.py" --check-bundle --experiment train_general_big_map_test10_SAC
# shellcheck disable=SC1091
source "$OLD_PROJECT/spot_rl_energy_navigation/cloud/env.sh"
[[ -x "${GENERAL_MAP_ISAACLAB:-}" && -x "${SPOT_RUNTIME_DIR:-}/venv/bin/python" ]] || {
    echo 'Existing runtime is incomplete. Use fresh setup instead.' >&2; exit 1;
}
export SPOT_ZED_USD="$PROJECT/.cloud_assets/ZED_X.usdc"
"$SPOT_RUNTIME_DIR/venv/bin/python" "$CLOUD/verify.py" --runtime --experiment train_general_big_map_test10_SAC
NEW_ENV="$CLOUD/.env.$$.tmp"
trap 'rm -f "$NEW_ENV"' EXIT
{
    echo '# Generated by setup_test10.sh; software reused, test10 assets independent.'
    printf 'export SPOT_RUNTIME_DIR=%q\n' "$SPOT_RUNTIME_DIR"
    printf 'export GENERAL_MAP_ISAACLAB=%q\n' "$GENERAL_MAP_ISAACLAB"
    printf 'export SPOT_ZED_USD=%q\n' "$SPOT_ZED_USD"
    printf 'export PATH=%q:"$PATH"\n' "$SPOT_RUNTIME_DIR/venv/bin"
    echo 'export PYTHONNOUSERSITE=1'
    if [[ "$EUID" == 0 ]]; then echo 'export OMNI_KIT_ALLOW_ROOT=1'; fi
} > "$NEW_ENV"
mv "$NEW_ENV" "$CLOUD/env.sh"
if [[ "$SKIP_PROBE" == 0 ]]; then
    bash "$CLOUD/run.sh" --python "$CLOUD/../train_general_big_map_test10_SAC/probe_env.py" --headless --device cuda:0
    echo '[OK] Existing runtime and test10 simulator check passed.'
else
    echo '[OK] Existing CUDA/DINO runtime verified; simulator NOT checked.'
fi
